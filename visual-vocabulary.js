const VISUAL_VOCABULARY_GROUPS = PROMPT_CONTROL_GROUPS.map((group) => {
  const meta = VISUAL_VOCABULARY_META[group.id];
  if (!meta || meta.definitions.length !== group.options.length) {
    throw new Error(`视觉词典数据与工坊控制项不一致：${group.id}`);
  }
  return {
    ...group,
    icon: meta.icon,
    intro: meta.intro,
    options: group.options.map((option, index) => {
      const mechanics = VISUAL_VOCABULARY_MECHANICS[option.zh];
      if (!mechanics) throw new Error(`视觉词典缺少独立机制记录：${option.zh}`);
      return {
        ...option,
        ...mechanics,
        definition: meta.definitions[index],
        index
      };
    })
  };
});

const VISUAL_VOCABULARY_COUNT = VISUAL_VOCABULARY_GROUPS.reduce((total, group) => total + group.options.length, 0);
