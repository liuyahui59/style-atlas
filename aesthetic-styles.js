function createAestheticStyle(config) {
  const prompt = AESTHETIC_PROMPT_DATA[config.id];
  const visualGenes = config.visualGenes.map(([zh, en]) => ({ zh, en }));
  return {
    ...config,
    visualGenes,
    promptZh: [`${config.nameZh}视觉语言`, ...visualGenes.map((gene) => gene.zh)],
    promptEn: [`${config.nameEn} visual language`, ...visualGenes.map((gene) => gene.en)],
    aiPrompt: {
      zh: prompt.zh,
      en: `Preserve the user-defined subjects, count, actions, setting, identities, and narrative relationships. User-specified composition, camera, aspect ratio, and exact text take priority. Do not add subjects, props, or story elements. Use ${config.nameEn} as the sole dominant visual style. Required execution details: ${visualGenes.map((gene) => gene.en).join(", ")}. Keep composition, form, palette, lighting, and surface treatment coherent. Apply style-appropriate typography only when the user requests text; otherwise add no text.`,
      negative: prompt.negative
    },
    artwork: { src: `assets/artworks/${config.id}.jpg` }
  };
}

STYLE_DATA.push(...NEW_AESTHETIC_STYLE_CONFIGS.map(createAestheticStyle));

Object.entries(AESTHETIC_PROMPT_DATA).forEach(([id, prompt]) => {
  const style = STYLE_DATA.find((item) => item.id === id);
  if (!style) throw new Error(`Missing style for aesthetic prompt: ${id}`);
  style.aiPrompt = { ...style.aiPrompt, zh: prompt.zh, negative: prompt.negative };
});

FILTER_GROUPS.type = [...new Set(STYLE_DATA.map((style) => style.type))];
FILTER_GROUPS.region = [...new Set(STYLE_DATA.map((style) => style.region))];
FILTER_GROUPS.traits = [...new Set(STYLE_DATA.flatMap((style) => style.traits))];
FILTER_GROUPS.fields = [...new Set(STYLE_DATA.flatMap((style) => style.fields))];
