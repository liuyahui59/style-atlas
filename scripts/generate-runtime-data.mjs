import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { evaluateClassicExpression, loadClassicScripts, STYLE_SOURCE_FILES } from "./lib/classic-script-loader.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "style-runtime-data.js");
const detailOutputPath = resolve(root, "style-detail-data.js");
const checkOnly = process.argv.includes("--check");
const context = await loadClassicScripts(root, STYLE_SOURCE_FILES);

const sourceStyles = JSON.parse(JSON.stringify(evaluateClassicExpression(context, "STYLE_DATA")));
const filters = JSON.parse(JSON.stringify(evaluateClassicExpression(context, "FILTER_GROUPS")));
const runtimeFields = [
  "id", "nameZh", "nameEn", "aliases", "type", "period", "year", "detailedRegion",
  "broadRegion", "broadRegions", "visualHistory", "visualHistoryShort", "visualHistoryTime",
  "traits", "fields", "genes", "palette", "related", "artwork"
];
const detailFields = ["summary", "recognition", "influencedBy", "influenced", "sources"];
const styles = sourceStyles.map((style) => Object.fromEntries(
  runtimeFields.flatMap((field) => field in style ? [[field, style[field]]] : [])
));
const details = Object.fromEntries(sourceStyles.map((style) => [style.id, Object.fromEntries(
  detailFields.flatMap((field) => field in style ? [[field, style[field]]] : [])
)]));

const output = `// Generated by scripts/generate-runtime-data.mjs. Edit source data, then regenerate.\nconst STRICT_STYLE_COUNT = ${styles.length};\nconst FILTER_GROUPS = Object.freeze(${JSON.stringify(filters)});\nconst STYLE_DATA = Object.freeze(${JSON.stringify(styles)});\n`;
const detailOutput = `// Generated by scripts/generate-runtime-data.mjs. Edit source data, then regenerate.\nconst STYLE_DETAIL_DATA = Object.freeze(${JSON.stringify(details)});\n`;

if (checkOnly) {
  const existing = await readFile(outputPath, "utf8").catch(() => null);
  if (existing !== output) {
    console.error("style-runtime-data.js is stale or missing");
    process.exitCode = 1;
  }
  const existingDetails = await readFile(detailOutputPath, "utf8").catch(() => null);
  if (existingDetails !== detailOutput) {
    console.error("style-detail-data.js is stale or missing");
    process.exitCode = 1;
  }
  if (existing === output && existingDetails === detailOutput) {
    console.log(`Validated compact runtime data for ${styles.length} styles`);
  }
} else {
  await writeFile(outputPath, output);
  await writeFile(detailOutputPath, detailOutput);
  console.log(`Generated compact runtime data for ${styles.length} styles`);
}
